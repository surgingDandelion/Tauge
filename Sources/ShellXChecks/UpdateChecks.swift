import Foundation
import ShellXKit

// Offline checks for the GitHub-tag updater. Everything here is pure parsing:
// no network, so the suite stays fast and deterministic on CI.

private func releaseJSON(
    tagName: String,
    draft: Bool = false,
    prerelease: Bool = false,
    htmlURL: String = "https://github.com/surgingDandelion/Tauge/releases/tag/v1.1.0",
    includeArchive: Bool = true,
    includeChecksums: Bool = true,
    archiveURL: String? = nil,
    checksumsURL: String = "https://github.com/surgingDandelion/Tauge/releases/download/v1.1.0/SHA256SUMS.txt",
    body: String = "  Fixed the updater.\n"
) -> Data {
    let version = tagName.hasPrefix("v") || tagName.hasPrefix("V") ? String(tagName.dropFirst()) : tagName
    var assets: [[String: Any]] = []
    if includeArchive {
        assets.append([
            "name": "Tauge-\(version).zip",
            "browser_download_url": archiveURL ?? "https://github.com/surgingDandelion/Tauge/releases/download/v1.1.0/Tauge-\(version).zip",
            "size": 1234,
        ])
    }
    if includeChecksums {
        assets.append([
            "name": "SHA256SUMS.txt",
            "browser_download_url": checksumsURL,
            "size": 100,
        ])
    }
    let payload: [String: Any] = [
        "tag_name": tagName,
        "name": "Tauge \(version)",
        "body": body,
        "html_url": htmlURL,
        "published_at": "2026-11-18T07:00:00Z",
        "draft": draft,
        "prerelease": prerelease,
        "assets": assets,
    ]
    return try! JSONSerialization.data(withJSONObject: payload, options: [.sortedKeys])
}

private func expectUpdateError(
    _ expected: TaugeUpdateError,
    _ body: () throws -> TaugeUpdateCheck,
    _ message: String,
    line: Int = #line
) {
    do {
        _ = try body()
        expect(false, message + " (no error)", line: line)
    } catch let error as TaugeUpdateError {
        expectEqual(error, expected, message, line: line)
    } catch {
        expect(false, message + " (wrong error: \(error))", line: line)
    }
}

func runUpdateChecks() {
    run("update.version parses tags and normalises components") {
        expectEqual(TaugeVersion("v1.2.3")?.components, [1, 2, 3], "v prefix is accepted")
        expectEqual(TaugeVersion("1.2")?.description, "1.2.0", "missing patch becomes zero")
        expectEqual(TaugeVersion("V2.0")?.description, "2.0.0", "capital V is accepted")
        expectEqual(TaugeVersion("1.2.3+build.7"), TaugeVersion("1.2.3"), "build metadata is ignored")
        expect(TaugeVersion("1.2.3-beta.2") == TaugeVersion("1.2.3-beta.2"), "prerelease equality")
        expect(TaugeVersion("1.2.3-beta.2")! < TaugeVersion("1.2.3")!, "final release wins over prerelease")
        expect(TaugeVersion("1.2.3-beta.2")! < TaugeVersion("1.2.3-beta.11")!, "numeric prerelease identifiers compare numerically")
        expect(TaugeVersion("1.10.0")! > TaugeVersion("1.9.9")!, "minor component is numeric, not lexical")
        expect(TaugeVersion("") == nil, "empty version is rejected")
        expect(TaugeVersion("v") == nil, "bare v is rejected")
        expect(TaugeVersion("1.2.x") == nil, "non-numeric field is rejected")
        expect(TaugeVersion("1..2") == nil, "empty field is rejected")
        expect(TaugeVersion("1.2.3-") == nil, "empty prerelease is rejected")
    }

    run("update.checksums parses shasum output") {
        let digest = String(repeating: "a", count: 64)
        let other = String(repeating: "b", count: 64)
        let text = """
        # generated by shasum
        \(digest)  Tauge-1.1.0.zip
        \(other) *Tauge-1.1.0.dmg

        not-a-checksum  ignored.zip
        \(String(repeating: "c", count: 63))  short.zip
        \(digest)  Tauge-1.1.0.zip
        """
        let table = TaugeChecksum.parse(text)
        expectEqual(table["Tauge-1.1.0.zip"], digest, "zip digest")
        expectEqual(table["Tauge-1.1.0.dmg"], other, "star prefix is stripped")
        expect(table["ignored.zip"] == nil, "malformed digest is ignored")
        expect(table["short.zip"] == nil, "short digest is ignored")
        expectEqual(TaugeChecksum.expectedSHA256(for: "Tauge-1.1.0.dmg", in: text), other, "lookup by file name")
        expect(TaugeChecksum.expectedSHA256(for: "missing.zip", in: text) == nil, "missing file has no checksum")
    }

    run("update.evaluate finds a newer stable release") {
        let data = releaseJSON(tagName: "v1.1.0")
        switch try TaugeUpdateService.evaluate(releaseData: data, currentVersion: "1.0.1") {
        case .available(let update):
            expectEqual(update.version, TaugeVersion("1.1.0")!, "release version comes from the tag")
            expectEqual(update.tagName, "v1.1.0", "tag is preserved")
            expectEqual(update.archiveName, "Tauge-1.1.0.zip", "the ZIP asset is selected")
            expectEqual(update.archiveSize, 1234, "asset size is carried over")
            expectEqual(update.notes, "Fixed the updater.", "release notes are trimmed")
            expectEqual(update.checksumsURL.lastPathComponent, "SHA256SUMS.txt", "checksum asset is selected")
        case .upToDate:
            expect(false, "expected an available update")
        }
    }

    run("update.evaluate reports up to date without requiring assets") {
        let data = releaseJSON(tagName: "v1.1.0", includeArchive: false, includeChecksums: false)
        switch try TaugeUpdateService.evaluate(releaseData: data, currentVersion: "1.1.0") {
        case .upToDate(let current):
            expectEqual(current, TaugeVersion("1.1.0")!, "same version is up to date")
        case .available:
            expect(false, "same version must not be offered")
        }
        switch try TaugeUpdateService.evaluate(releaseData: data, currentVersion: "2.0.0") {
        case .upToDate:
            break
        case .available:
            expect(false, "newer current version must not be offered an older release")
        }
    }

    run("update.evaluate rejects drafts, prereleases and malformed payloads") {
        expectUpdateError(.noStableRelease, {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", draft: true), currentVersion: "1.0.1")
        }, "draft releases are not offered")
        expectUpdateError(.noStableRelease, {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", prerelease: true), currentVersion: "1.0.1")
        }, "prereleases are not offered")
        expectUpdateError(.invalidRelease, {
            try TaugeUpdateService.evaluate(releaseData: Data("not json".utf8), currentVersion: "1.0.1")
        }, "garbage JSON is rejected")
        expectUpdateError(.invalidVersion("1.0.x"), {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0"), currentVersion: "1.0.x")
        }, "an invalid running version is reported")
        expectUpdateError(.invalidVersion("release-1"), {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "release-1"), currentVersion: "1.0.1")
        }, "an invalid tag is reported")
    }

    run("update.evaluate requires the expected assets over HTTPS") {
        expectUpdateError(.missingAsset("Tauge-1.1.0.zip"), {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", includeArchive: false), currentVersion: "1.0.1")
        }, "a release without the ZIP is rejected")
        expectUpdateError(.missingAsset("SHA256SUMS.txt"), {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", includeChecksums: false), currentVersion: "1.0.1")
        }, "a release without checksums is rejected")
        expectUpdateError(.insecureURL, {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", htmlURL: "http://example.com/release"), currentVersion: "1.0.1")
        }, "an HTTP release page is rejected")
        expectUpdateError(.insecureURL, {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", archiveURL: "http://example.com/Tauge-1.1.0.zip"), currentVersion: "1.0.1")
        }, "an HTTP archive is rejected")
        expectUpdateError(.insecureURL, {
            try TaugeUpdateService.evaluate(releaseData: releaseJSON(tagName: "v1.1.0", checksumsURL: "http://example.com/SHA256SUMS.txt"), currentVersion: "1.0.1")
        }, "an HTTP checksum file is rejected")
    }
}
